create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Admin-only direct database policies; API remains the documented administration contract.
do $$ begin
  if not exists (select 1 from pg_policies where policyname='admins_manage_categories' and tablename='categories') then
    create policy admins_manage_categories on public.categories for all using (public.is_admin()) with check (public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where policyname='admins_manage_products' and tablename='products') then
    create policy admins_manage_products on public.products for all using (public.is_admin()) with check (public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where policyname='admins_manage_variants' and tablename='variants') then
    create policy admins_manage_variants on public.variants for all using (public.is_admin()) with check (public.is_admin());
  end if;
  if not exists (select 1 from pg_policies where policyname='admins_manage_skus' and tablename='skus') then
    create policy admins_manage_skus on public.skus for all using (public.is_admin()) with check (public.is_admin());
  end if;
end $$;
